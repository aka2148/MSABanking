[CmdletBinding()]
param(
    [string]$LoginPath = 'moneypal-audit',
    [string]$UserName,
    [string]$HostName,
    [int]$Port = 0,
    [string]$OutputPath = (Join-Path $PSScriptRoot 'generated-rollback-audit-columns.sql'),
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'AuditColumns.Common.psm1') -Force

function Get-ManifestKey {
    param([string]$Schema, [string]$Table, [string]$Type, [string]$Name)
    return (@($Schema, $Table, $Type, $Name) -join [char]0)
}

$metadata = Get-AuditDatabaseMetadata -LoginPath $LoginPath -UserName $UserName -HostName $HostName -Port $Port
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by rollback-audit-columns.ps1; review before execution.')
$lines.Add('-- This is a compensating script; MySQL DDL auto-commits.')
$lines.Add('SET SESSION time_zone = ''+00:00'';')
$lines.Add('SET @audit_columns_migration_mode = 1;')
$lines.Add('')

$manifestTableName = '_codex_audit_columns_manifest'
$manifestRef = '`moneypal_fd`.`_codex_audit_columns_manifest`'
$routineName = '_codex_audit_columns_backfill_v1'
$routineRecorded = $metadata.Manifest.ContainsKey((Get-ManifestKey 'moneypal_fd' $manifestTableName 'ROUTINE_CREATED' $routineName))
$routineExists = @($metadata.Routines | Where-Object { $_ -eq $routineName }).Count -gt 0
$routineWasDropped = $routineRecorded -and $routineExists
if ($routineWasDropped) {
    $lines.Add("DROP PROCEDURE IF EXISTS ``moneypal_fd``.``$routineName``;")
}
$manifestCreatedByRun = $metadata.Manifest.ContainsKey((Get-ManifestKey 'moneypal_fd' $manifestTableName 'MANIFEST_TABLE_CREATED' $manifestTableName))
$recordedTriggers = [System.Collections.Generic.List[object]]::new()
$recordedColumns = [System.Collections.Generic.Dictionary[string,System.Collections.Generic.List[string]]]::new([System.StringComparer]::Ordinal)

foreach ($manifestKey in $metadata.Manifest.Keys) {
    $parts = $manifestKey.Split([char[]]@([char]0))
    if ($parts.Count -ne 4) { continue }
    $schema = $parts[0]
    $tableName = $parts[1]
    $objectType = $parts[2]
    $objectName = $parts[3]
    $table = @($metadata.Tables | Where-Object { $_.Schema -eq $schema -and $_.Name -eq $tableName } | Select-Object -First 1)
    if ($objectType -eq 'TRIGGER_CREATED' -and $table.Count -gt 0) {
        $trigger = @($table[0].Triggers | Where-Object { $_.Name -eq $objectName })
        if ($trigger.Count -gt 0) {
            $recordedTriggers.Add([pscustomobject]@{ Schema = $schema; Name = $objectName })
        }
    }
    if ($objectType -eq 'COLUMN_CREATED' -and $table.Count -gt 0) {
        $exists = @($table[0].Columns | Where-Object { $_.Name -eq $objectName }).Count -gt 0
        if ($exists) {
            $key = Get-ManifestKey $schema $tableName '' ''
            if (-not $recordedColumns.ContainsKey($key)) { $recordedColumns[$key] = [System.Collections.Generic.List[string]]::new() }
            $recordedColumns[$key].Add($objectName)
        }
    }
}

foreach ($trigger in $recordedTriggers) {
    $lines.Add("DROP TRIGGER IF EXISTS $(ConvertTo-AuditSqlIdentifier $trigger.Schema).$(ConvertTo-AuditSqlIdentifier $trigger.Name);")
}

foreach ($table in $metadata.Tables) {
    if ($manifestCreatedByRun -and $table.Schema -eq 'moneypal_fd' -and $table.Name -eq $manifestTableName) { continue }
    $key = Get-ManifestKey $table.Schema $table.Name '' ''
    if (-not $recordedColumns.ContainsKey($key)) { continue }
    $drops = @($recordedColumns[$key] | Select-Object -Unique | ForEach-Object { 'DROP COLUMN ' + (ConvertTo-AuditSqlIdentifier $_) })
    if ($drops.Count -gt 0) {
        $lines.Add("ALTER TABLE $(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name) $($drops -join ', ');")
    }
}

if ($manifestCreatedByRun) {
    $lines.Add("DROP TABLE IF EXISTS $manifestRef;")
} elseif ($metadata.ManifestExisted) {
    $lines.Add("DELETE FROM $manifestRef WHERE run_id = 'banking_audit_columns_v1';")
}

$lines.Add('SET @audit_columns_migration_mode = 0;')
$lines.Add("SELECT @@hostname AS mysql_host, @@port AS mysql_port, @@version AS mysql_version, UTC_TIMESTAMP(6) AS rollback_completed_at;")

$resolvedOutput = [System.IO.Path]::GetFullPath($OutputPath)
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($resolvedOutput)) | Out-Null
[System.IO.File]::WriteAllLines($resolvedOutput, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "Connected server: $($metadata.Host):$($metadata.Port) (MySQL $($metadata.Version))"
Write-Host "Generated SQL: $resolvedOutput"
if ($metadata.Manifest.Count -eq 0) {
    Write-Host 'No apply manifest entries were found; generated SQL is a no-op.'
}

if ($Apply) {
    if ($metadata.Manifest.Count -eq 0) {
        Write-Host 'Nothing to roll back.'
    } else {
        Write-Host 'Applying rollback SQL...'
        Invoke-AuditMysqlFile -LoginPath $LoginPath -UserName $UserName -HostName $HostName -Port $Port -Path $resolvedOutput
        Write-Host 'Rollback completed. Verify the columns and confirm the application is operating as expected.'
    }
} else {
    Write-Host 'Generate-only mode; no schema or row changes were made. Re-run with -Apply to execute this generated SQL.'
}
