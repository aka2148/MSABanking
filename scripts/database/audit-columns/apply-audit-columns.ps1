[CmdletBinding()]
param(
    [string]$LoginPath = 'moneypal-audit',
    [string]$UserName,
    [string]$HostName,
    [int]$Port = 0,
    [string]$OutputPath = (Join-Path $PSScriptRoot 'generated-audit-columns.sql'),
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'AuditColumns.Common.psm1') -Force

function Add-ManifestRecord {
    param(
        [System.Collections.Generic.List[string]]$Lines,
        [string]$Schema,
        [string]$Table,
        [string]$Type,
        [string]$Name
    )
    $values = @(
        (ConvertTo-AuditSqlLiteral -Value 'banking_audit_columns_v1'),
        (ConvertTo-AuditSqlLiteral -Value $Schema),
        (ConvertTo-AuditSqlLiteral -Value $Table),
        (ConvertTo-AuditSqlLiteral -Value $Type),
        (ConvertTo-AuditSqlLiteral -Value $Name)
    ) -join ', '
    $Lines.Add("INSERT IGNORE INTO ``moneypal_fd``.``_codex_audit_columns_manifest`` (run_id,target_schema,target_table,object_type,object_name) VALUES ($values);")
}

function Get-ManifestKey {
    param([string]$Schema, [string]$Table, [string]$Type, [string]$Name)
    return (@($Schema, $Table, $Type, $Name) -join [char]0)
}

$metadata = Get-AuditDatabaseMetadata -LoginPath $LoginPath -UserName $UserName -HostName $HostName -Port $Port
$manifestSchema = 'moneypal_fd'
$manifestTableName = '_codex_audit_columns_manifest'
$manifestTable = "$(ConvertTo-AuditSqlIdentifier $manifestSchema).$(ConvertTo-AuditSqlIdentifier $manifestTableName)"
$procNameBare = '_codex_audit_columns_backfill_v1'
$procName = '`moneypal_fd`.`_codex_audit_columns_backfill_v1`'
$routineExists = @($metadata.Routines | Where-Object { $_ -eq $procNameBare }).Count -gt 0
$routineRecorded = $metadata.Manifest.ContainsKey((Get-ManifestKey $manifestSchema $manifestTableName 'ROUTINE_CREATED' $procNameBare))
if ($routineExists -and -not $routineRecorded) {
    throw "Routine name conflict: $manifestSchema.$procNameBare already exists but is not in this script's manifest. Inspect it before applying."
}
# Avoid adopting or overwriting a same-named trigger that was not recorded by this tool.
foreach ($table in $metadata.Tables) {
    foreach ($suffix in @('bi', 'bu')) {
        $triggerName = Get-AuditTriggerName -Schema $table.Schema -Table $table.Name -Suffix $suffix
        $alreadyExists = @($table.Triggers | Where-Object { $_.Name -eq $triggerName }).Count -gt 0
        $recorded = $metadata.Manifest.ContainsKey((Get-ManifestKey $table.Schema $table.Name 'TRIGGER_CREATED' $triggerName))
        if ($alreadyExists -and -not $recorded) {
            throw "Trigger name conflict: $($table.Schema).$triggerName already exists but is not in this script's manifest. Inspect it before applying."
        }
    }
}
$requestedColumns = @('host_timestamp', 'local_timestamp', 'crud_value', 'ldb_id')
$migrationIncomplete = $false
foreach ($table in $metadata.Tables) {
    $createdColumns = @($requestedColumns | Where-Object {
        $metadata.Manifest.ContainsKey((Get-ManifestKey $table.Schema $table.Name 'COLUMN_CREATED' $_))
    })
    $columnsFinalized = $metadata.Manifest.ContainsKey((Get-ManifestKey $table.Schema $table.Name 'COLUMNS_FINALIZED' ''))
    if ($createdColumns.Count -gt 0 -and -not $columnsFinalized) { $migrationIncomplete = $true }
    foreach ($suffix in @('bi', 'bu')) {
        $triggerName = Get-AuditTriggerName -Schema $table.Schema -Table $table.Name -Suffix $suffix
        if (@($table.Triggers | Where-Object { $_.Name -eq $triggerName }).Count -eq 0) {
            $migrationIncomplete = $true
        }
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by apply-audit-columns.ps1; review before execution.')
$lines.Add('-- The script intentionally runs without a transaction because MySQL DDL auto-commits.')
$lines.Add('SET SESSION time_zone = ''+00:00'';')
$lines.Add('SET SESSION autocommit = 1;')
$lines.Add('SET @audit_columns_migration_mode = 1;')
$lines.Add('SET @audit_columns_migration_time = UTC_TIMESTAMP(6);')
$lines.Add('')

if (-not $metadata.ManifestExisted) {
    $lines.Add("CREATE TABLE IF NOT EXISTS $manifestTable (")
    $lines.Add('  run_id VARCHAR(100) NOT NULL,')
    $lines.Add('  target_schema VARCHAR(64) NOT NULL,')
    $lines.Add('  target_table VARCHAR(64) NOT NULL,')
    $lines.Add('  object_type VARCHAR(40) NOT NULL,')
    $lines.Add('  object_name VARCHAR(128) NOT NULL,')
    $lines.Add('  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),')
    $lines.Add('  PRIMARY KEY (run_id,target_schema,target_table,object_type,object_name)')
    $lines.Add(') ENGINE=InnoDB;')
    Add-ManifestRecord -Lines $lines -Schema $manifestSchema -Table $manifestTableName -Type 'MANIFEST_TABLE_CREATED' -Name $manifestTableName
    $lines.Add('')
}

foreach ($table in $metadata.Tables) {
    $existingNames = @($table.Columns | ForEach-Object { $_.Name })
    $missing = @($requestedColumns | Where-Object { $existingNames -notcontains $_ })
    if ($missing.Count -gt 0) {
        foreach ($column in $missing) {
            Add-ManifestRecord -Lines $lines -Schema $table.Schema -Table $table.Name -Type 'COLUMN_CREATED' -Name $column
        }
        $definitions = foreach ($column in $missing) {
            switch ($column) {
                'host_timestamp' { 'ADD COLUMN `host_timestamp` DATETIME(6) NULL' }
                'local_timestamp' { 'ADD COLUMN `local_timestamp` DATETIME(6) NULL' }
                'crud_value' { 'ADD COLUMN `crud_value` CHAR(1) NULL' }
                'ldb_id' { 'ADD COLUMN `ldb_id` BIGINT NULL' }
            }
        }
        $lines.Add("ALTER TABLE $(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name) $($definitions -join ', ');")
    }
}
$lines.Add('')

$backfillTables = @($metadata.Tables | Where-Object {
    $columns = @($_.Columns | ForEach-Object { $_.Name })
    (-not $metadata.Manifest.ContainsKey((Get-ManifestKey $_.Schema $_.Name 'BACKFILL_DONE' ''))) -or
    @($requestedColumns | Where-Object { $columns -notcontains $_ }).Count -gt 0
})
$routineDropped = $false
if ($backfillTables.Count -gt 0) {
    $lines.Add("DROP PROCEDURE IF EXISTS $procName;")
    Add-ManifestRecord -Lines $lines -Schema $manifestSchema -Table $manifestTableName -Type 'ROUTINE_CREATED' -Name $procNameBare
    $lines.Add('DELIMITER $$')
    $lines.Add("CREATE PROCEDURE $procName()")
    $lines.Add('BEGIN')
    $lines.Add('  DECLARE v_rows BIGINT DEFAULT 1;')
    foreach ($table in $backfillTables) {
        $qualifiedTable = "$(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name)"
        $columnNames = @($table.Columns | ForEach-Object { $_.Name })
        $candidateColumns = @($table.Columns | Where-Object {
            $_.Type -in @('datetime', 'timestamp') -and
            $_.Name -match '(^|_)(updated|modified)_(at|date)$'
        } | Sort-Object `
            @{ Expression = { if ($_.Name -match '(^|_)(updated|modified)_') { 0 } else { 1 } } },
            @{ Expression = { $_.Ordinal } })
        $candidateColumns += @($table.Columns | Where-Object {
            $_.Type -in @('datetime', 'timestamp') -and
            $_.Name -match '(^|_)(created|inserted)_(at|date)$'
        } | Sort-Object `
            @{ Expression = { if ($_.Name -match '(^|_)created_') { 0 } else { 1 } } },
            @{ Expression = { $_.Ordinal } })
        $candidates = @($candidateColumns | ForEach-Object { ConvertTo-AuditSqlIdentifier $_.Name } | Select-Object -Unique)
        if ($candidates.Count -gt 0) {
            $timestampExpression = 'COALESCE(' + (($candidates + '@audit_columns_migration_time') -join ', ') + ')'
        } else {
            $timestampExpression = '@audit_columns_migration_time'
        }
        $primaryKey = @($table.Columns | Where-Object { $_.Key -eq 'PRI' } | Sort-Object Ordinal)
        $orderBy = ''
        if ($primaryKey.Count -gt 0) {
            $orderBy = ' ORDER BY ' + (($primaryKey | ForEach-Object { ConvertTo-AuditSqlIdentifier $_.Name }) -join ', ')
        }
        $lines.Add('  SET v_rows = 1;')
        $lines.Add('  WHILE v_rows > 0 DO')
        $lines.Add("    UPDATE $qualifiedTable SET host_timestamp=COALESCE(host_timestamp,$timestampExpression), local_timestamp=COALESCE(local_timestamp,$timestampExpression), crud_value=COALESCE(crud_value,'C'), ldb_id=COALESCE(ldb_id,$($metadata.SchemaIds[$table.Schema])) WHERE host_timestamp IS NULL OR local_timestamp IS NULL OR crud_value IS NULL OR ldb_id IS NULL$orderBy LIMIT 1000;")
        $lines.Add('    SET v_rows = ROW_COUNT();')
        $lines.Add('  END WHILE;')
        $backfillMarkerValues = @(
            (ConvertTo-AuditSqlLiteral 'banking_audit_columns_v1'),
            (ConvertTo-AuditSqlLiteral $table.Schema),
            (ConvertTo-AuditSqlLiteral $table.Name),
            (ConvertTo-AuditSqlLiteral 'BACKFILL_DONE'),
            "''",
            '@audit_columns_migration_time',
            '@audit_columns_migration_time',
            "'C'",
            [string]$metadata.SchemaIds['moneypal_fd']
        ) -join ', '
        $lines.Add("  INSERT IGNORE INTO $manifestTable (run_id,target_schema,target_table,object_type,object_name,host_timestamp,local_timestamp,crud_value,ldb_id) VALUES ($backfillMarkerValues);")
    }
    $lines.Add('END$$')
    $lines.Add('DELIMITER ;')
    $lines.Add("CALL $procName();")
    $lines.Add("DROP PROCEDURE $procName;")
    $routineDropped = $true
}
if ($routineExists -and -not $routineDropped) {
    $lines.Add("DROP PROCEDURE IF EXISTS $procName;")
}
$lines.Add('')

$finalizationTables = @($metadata.Tables | Where-Object {
    $_.Schema -ne $manifestSchema -or $_.Name -ne $manifestTableName
}) + @($metadata.Tables | Where-Object {
    $_.Schema -eq $manifestSchema -and $_.Name -eq $manifestTableName
})
foreach ($table in $finalizationTables) {
    $createdByScript = @(
        foreach ($manifestKey in $metadata.Manifest.Keys) {
            $parts = $manifestKey.Split([char[]]@([char]0))
            if ($parts.Count -eq 4 -and $parts[0] -eq $table.Schema -and $parts[1] -eq $table.Name -and $parts[2] -eq 'COLUMN_CREATED') {
                $parts[3]
            }
        }
    )
    $initialColumnNames = @($table.Columns | ForEach-Object { $_.Name })
    $newlyMissing = @($requestedColumns | Where-Object { $initialColumnNames -notcontains $_ })
    $createdByScript += $newlyMissing
    $createdByScript = @($createdByScript | Select-Object -Unique)
    $alreadyFinalized = $metadata.Manifest.ContainsKey((Get-ManifestKey $table.Schema $table.Name 'COLUMNS_FINALIZED' ''))
    if ($migrationIncomplete -and $createdByScript.Count -gt 0) {
        if ($table.Schema -eq $manifestSchema -and $table.Name -eq $manifestTableName) {
            $lines.Add("UPDATE $manifestTable SET host_timestamp=COALESCE(host_timestamp,created_at,@audit_columns_migration_time), local_timestamp=COALESCE(local_timestamp,created_at,@audit_columns_migration_time), crud_value=COALESCE(crud_value,'C'), ldb_id=COALESCE(ldb_id,1) WHERE host_timestamp IS NULL OR local_timestamp IS NULL OR crud_value IS NULL OR ldb_id IS NULL;")
        } else {
        $candidateColumns = @($table.Columns | Where-Object {
            $_.Type -in @('datetime', 'timestamp') -and
            $_.Name -match '(^|_)(updated|modified)_(at|date)$'
        } | Sort-Object `
            @{ Expression = { if ($_.Name -match '(^|_)(updated|modified)_') { 0 } else { 1 } } },
            @{ Expression = { $_.Ordinal } })
        $candidateColumns += @($table.Columns | Where-Object {
            $_.Type -in @('datetime', 'timestamp') -and
            $_.Name -match '(^|_)(created|inserted)_(at|date)$'
        } | Sort-Object `
            @{ Expression = { if ($_.Name -match '(^|_)created_') { 0 } else { 1 } } },
            @{ Expression = { $_.Ordinal } })
        $candidates = @($candidateColumns | ForEach-Object { ConvertTo-AuditSqlIdentifier $_.Name } | Select-Object -Unique)
        if ($candidates.Count -gt 0) {
            $timestampExpression = 'COALESCE(' + (($candidates + '@audit_columns_migration_time') -join ', ') + ')'
        } else {
            $timestampExpression = '@audit_columns_migration_time'
        }
        $qualifiedTable = "$(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name)"
        $schemaLdbId = $metadata.SchemaIds[$table.Schema]
        $lines.Add("UPDATE $qualifiedTable SET host_timestamp=COALESCE(host_timestamp,$timestampExpression), local_timestamp=COALESCE(local_timestamp,$timestampExpression), crud_value=COALESCE(crud_value,'C'), ldb_id=COALESCE(ldb_id,$schemaLdbId) WHERE host_timestamp IS NULL OR local_timestamp IS NULL OR crud_value IS NULL OR ldb_id IS NULL;")
        }
    }
    if ($createdByScript.Count -eq 0 -or ($alreadyFinalized -and $newlyMissing.Count -eq 0)) { continue }
    $changes = foreach ($column in $createdByScript) {
        switch ($column) {
            'host_timestamp' { 'MODIFY COLUMN `host_timestamp` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)' }
            'local_timestamp' { 'MODIFY COLUMN `local_timestamp` DATETIME(6) NULL DEFAULT NULL' }
            'crud_value' { "MODIFY COLUMN ``crud_value`` CHAR(1) NOT NULL DEFAULT 'C'" }
            'ldb_id' { "MODIFY COLUMN ``ldb_id`` BIGINT NOT NULL DEFAULT $($metadata.SchemaIds[$table.Schema])" }
        }
    }
    $lines.Add("ALTER TABLE $(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name) $($changes -join ', ');")
    Add-ManifestRecord -Lines $lines -Schema $table.Schema -Table $table.Name -Type 'COLUMNS_FINALIZED' -Name ''
}
$lines.Add('')

foreach ($table in $metadata.Tables) {
    foreach ($suffix in @('bi', 'bu')) {
        $triggerName = Get-AuditTriggerName -Schema $table.Schema -Table $table.Name -Suffix $suffix
        if (@($table.Triggers | Where-Object { $_.Name -eq $triggerName }).Count -gt 0) { continue }

        $event = if ($suffix -eq 'bi') { 'INSERT' } else { 'UPDATE' }
        $following = @($table.Triggers | Where-Object { $_.Timing -eq 'BEFORE' -and $_.Event -eq $event } | Sort-Object ActionOrder | Select-Object -Last 1)
        $ordering = if ($following.Count -gt 0) { ' FOLLOWS ' + (ConvertTo-AuditSqlIdentifier $following[0].Name) } else { '' }
        $triggerRef = "$(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $triggerName)"
        $tableRef = "$(ConvertTo-AuditSqlIdentifier $table.Schema).$(ConvertTo-AuditSqlIdentifier $table.Name)"
        Add-ManifestRecord -Lines $lines -Schema $table.Schema -Table $table.Name -Type 'TRIGGER_CREATED' -Name $triggerName
        $lines.Add('DELIMITER $$')
        $lines.Add("CREATE TRIGGER $triggerRef BEFORE $event ON $tableRef FOR EACH ROW$ordering")
        $lines.Add('BEGIN')
        $lines.Add('  IF COALESCE(@audit_columns_migration_mode,0) = 0 THEN')
        $lines.Add('    SET NEW.`host_timestamp` = UTC_TIMESTAMP(6);')
        if ($event -eq 'INSERT') { $lines.Add("    SET NEW.`crud_value` = 'C';") }
        else { $lines.Add("    SET NEW.`crud_value` = 'U';") }
        $lines.Add('  END IF;')
        $lines.Add('END$$')
        $lines.Add('DELIMITER ;')
    }
}

if ($migrationIncomplete) {
    $lines.Add("UPDATE $manifestTable SET local_timestamp=COALESCE(local_timestamp,created_at,@audit_columns_migration_time) WHERE local_timestamp IS NULL;")
}
$lines.Add('SET @audit_columns_migration_mode = 0;')
$lines.Add("SELECT @@hostname AS mysql_host, @@port AS mysql_port, @@version AS mysql_version, UTC_TIMESTAMP(6) AS completed_at;")

$resolvedOutput = [System.IO.Path]::GetFullPath($OutputPath)
[System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($resolvedOutput)) | Out-Null
[System.IO.File]::WriteAllLines($resolvedOutput, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "Connected server: $($metadata.Host):$($metadata.Port) (MySQL $($metadata.Version))"
Write-Host "Discovered $($metadata.Tables.Count) base tables (including the manifest helper table when it does not yet exist)."
Write-Host "Generated SQL: $resolvedOutput"

if ($Apply) {
    Write-Host 'Applying generated SQL...'
    Invoke-AuditMysqlFile -LoginPath $LoginPath -UserName $UserName -HostName $HostName -Port $Port -Path $resolvedOutput
    Write-Host 'Apply completed. Run verify-audit-columns.sql and inspect the manifest.'
} else {
    Write-Host 'Generate-only mode; no schema or row changes were made. Re-run with -Apply to execute this generated SQL.'
}
